CREATE TABLE IF NOT EXISTS usuarios (
    id_usuario BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_completo VARCHAR(150) NOT NULL,
    correo VARCHAR(254) NOT NULL,
    rol VARCHAR(20) NOT NULL
        CHECK (rol IN ('Estudiante', 'Docente', 'Mantenimiento')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_usuarios_correo UNIQUE (correo)
);

CREATE TABLE IF NOT EXISTS ubicaciones (
    id_ubicacion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bloque VARCHAR(80) NOT NULL,
    salon VARCHAR(80) NOT NULL,
    descripcion VARCHAR(500),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_ubicacion_bloque_salon UNIQUE (bloque, salon)
);

CREATE TABLE IF NOT EXISTS reportes (
    id_reporte BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    descripcion_dano TEXT NOT NULL,
    id_ubicacion BIGINT NOT NULL REFERENCES ubicaciones (id_ubicacion),
    id_usuario_reporta BIGINT NOT NULL REFERENCES usuarios (id_usuario),
    estado VARCHAR(20) NOT NULL DEFAULT 'Pendiente'
        CHECK (estado IN ('Pendiente', 'En Proceso', 'Resuelto')),
    fecha_reporte TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS historial_estados (
    id_historial BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_reporte BIGINT NOT NULL REFERENCES reportes (id_reporte),
    estado_anterior VARCHAR(20)
        CHECK (estado_anterior IS NULL OR estado_anterior IN ('Pendiente', 'En Proceso', 'Resuelto')),
    estado_nuevo VARCHAR(20) NOT NULL
        CHECK (estado_nuevo IN ('Pendiente', 'En Proceso', 'Resuelto')),
    fecha_cambio TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    id_usuario_cambio BIGINT NOT NULL REFERENCES usuarios (id_usuario),
    observacion TEXT
);

-- El historial se inserta transaccionalmente desde ReporteService.
DROP TRIGGER IF EXISTS trg_reportes_historial_estado ON reportes;
DROP FUNCTION IF EXISTS registrar_cambio_estado_reporte();

CREATE INDEX IF NOT EXISTS idx_reportes_ubicacion ON reportes (id_ubicacion);
CREATE INDEX IF NOT EXISTS idx_reportes_usuario_reporta ON reportes (id_usuario_reporta);
CREATE INDEX IF NOT EXISTS idx_reportes_estado_fecha ON reportes (estado, fecha_reporte DESC);
CREATE INDEX IF NOT EXISTS idx_historial_reporte_fecha ON historial_estados (id_reporte, fecha_cambio DESC);
CREATE INDEX IF NOT EXISTS idx_historial_usuario ON historial_estados (id_usuario_cambio);

